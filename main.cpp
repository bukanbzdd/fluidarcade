#include <string>
#include <vector>

void text_contains() {
    std::string text = "hidden harbor";
    std::string part = "harbor";
    bool found = false;
    for (std::size_t i = 0; i + part.size() <= text.size(); ++i) {
        bool match = true;
        for (std::size_t j = 0; j < part.size(); ++j) {
            if (text[i + j] != part[j]) { match = false; break; }
        }
        if (match) { found = true; break; }
    }
    (void)found;
}

void vector_max() {
    std::vector<int> values;
    values.push_back(11);
    values.push_back(29);
    values.push_back(7);
    int best = values[0];
    for (std::size_t i = 1; i < values.size(); ++i) {
        if (values[i] > best) best = values[i];
    }
    (void)best;
}

void sum_squares() {
    int acc = 0;
    for (int i = -5; i <= 5; ++i) acc += i * i;
    (void)acc;
}

void least_multiple() {
    int a = 6, b = 8;
    int x = a, y = b;
    while (y != 0) {
        int t = x % y;
        x = y;
        y = t;
    }
    int lcm = a / x * b;
    (void)lcm;
}

extern "C" int bright_prism();
extern "C" void noble_lantern();
extern "C" void vivid_summit();
extern "C" void ivory_canyon();
extern "C" void swift_boulder();

int main() {
    text_contains();
    vector_max();
    sum_squares();
    least_multiple();
    noble_lantern();
    vivid_summit();
    ivory_canyon();
    swift_boulder();
    return bright_prism();
}
